// Approximate SVG district polygons for all 77 Nepal districts
// Projected onto a 820×320 viewBox matching the existing province map.
//
// Coordinates derived from real district centroid lat/lng data and
// neighbour topology — these are simplified approximate shapes
// good enough for a choropleth heatmap at this resolution.
// ═══════════════════════════════════════════════════════════════

// Projection: Nepal bounding box
//   Lat:  26.30 (south) → 30.45 (north)
//   Lng:  80.04 (west)  → 88.20 (east)
// Maps to SVG: x: 0→820, y: 0→320 (north at top)
const W = 820, H = 320;
const LAT_MIN = 26.30, LAT_MAX = 30.45;
const LNG_MIN = 80.04, LNG_MAX = 88.20;
function proj(lat, lng) {
  const x = ((lng - LNG_MIN) / (LNG_MAX - LNG_MIN)) * W;
  const y = H - ((lat - LAT_MIN) / (LAT_MAX - LAT_MIN)) * H;
  return [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
}
function pts(...coords) {
  return coords.map(([la, ln]) => proj(la, ln).join(',')).join(' ');
}

